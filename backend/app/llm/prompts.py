# 提示詞與脈絡註記都是中文。模型會照抄看到的句子 ——
# 實測英文提問的答案裡出現「以下數據取自 Table 2 [1]：」，
# 那正是提示詞裡的範例句。因此語言指令必須明講：
# 這些是給你看的說明，不是可以搬進答案的字句。
